import sys
import os
import json
import numpy as np

def generate_mock_touchstone(config_path):
    print(f"Mock Palace Solver: Načítám {config_path}")
    
    with open(config_path, 'r') as f:
        config = json.load(f)
    
    freq_min = config['Solver']['Driven']['MinFreq']
    freq_max = config['Solver']['Driven']['MaxFreq']
    freq_step = config['Solver']['Driven']['FreqStep']
    
    output_dir = config['Problem'].get('Output', 'postpro')
    os.makedirs(output_dir, exist_ok=True)
    
    out_file = os.path.join(output_dir, "port-S.s1p")
    
    freqs = np.arange(freq_min, freq_max + freq_step/2, freq_step)
    
    # Generování simulovaného S11 - rezonance na 2.33 GHz
    f_res = 2.33
    Q = 50.0
    
    with open(out_file, 'w') as f:
        f.write("! Mock Touchstone file generated by Mock Palace\n")
        f.write("# GHz S MA R 50\n")
        
        for freq in freqs:
            # Model of a simple series RLC resonance
            delta = (freq - f_res) / f_res
            gamma_mag = np.sqrt((2*Q*delta)**2 / (1 + (2*Q*delta)**2))
            gamma_mag = max(gamma_mag, 0.05) # max -26 dB
            gamma_ang = 0.0 # simplified
            
            f.write(f"{freq:.4f} {gamma_mag:.4f} {gamma_ang:.4f}\n")
            
    print(f"Mock Palace Solver: Uloženo {out_file}")

if __name__ == "__main__":
    if len(sys.argv) > 1:
        generate_mock_touchstone(sys.argv[1])
    else:
        generate_mock_touchstone("config.json")
